// PreToolUse (Edit|Write): refuse edits to generated output and secret files.
// Exit code 2 blocks the tool call and shows stderr to Claude.
import { readFileSync } from "node:fs";

let input = {};
try {
  input = JSON.parse(readFileSync(0, "utf8"));
} catch {
  process.exit(0);
}

const file = String(input.tool_input?.file_path ?? "").replace(/\\/g, "/");

const blocked = [
  [/\/backend\/src\/generated\//, "generated by tsoa; edit backend/src/controllers and run `npm run build -w backend`"],
  [/\/backend\/public\//, "frontend build output; edit frontend/src and run `npm run build -w frontend`"],
  [/\/(engine|backend)\/dist\//, "compiled output; edit the TypeScript in src/"],
  [/\/node_modules\//, "dependencies; do not edit"],
  [/(^|\/)secret\.key$/, "dashboard encryption key; never edit or commit"],
  [/(^|\/)\.env(\..+)?$/, "environment secrets; never edit from here"],
  [/\/package-lock\.json$/, "managed by npm; run `npm install` instead"],
];

for (const [re, why] of blocked) {
  if (re.test(file)) {
    console.error(`Blocked edit to ${file}: ${why}.`);
    process.exit(2);
  }
}
process.exit(0);
